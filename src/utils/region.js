// 긴 이름부터 매칭 (예: "남양주" 가 "양주" 보다 먼저)
const CITY_ENTRIES = Object.entries(CITY_TO_SIDO).sort((a, b) => b[0].length - a[0].length)
const PREFIX_ENTRIES = SIDO_PREFIXES.slice().sort((a, b) => b[0].length - a[0].length)

/** 17개 표준 시/도 값인지 */
export function isSido(value) {
  return typeof value === 'string' && SIDO_SET.has(value)
}

/**
 * 주소/지역 자유 텍스트 → 표준 시/도 (17개 중 하나) 또는 null
 *   "서울특별시 강남구" → "서울", "강원특별자치도 원주시" → "강원",
 *   "충청북도 옥천군" → "충북", "김해" → "경남", "Seoul" → "서울", "가나" → null
 */
export function parseSido(text) {
  if (text == null) return null
  const s = String(text).trim().replace(/\s+/g, ' ').toLowerCase()
  if (!s) return null
  if (SIDO_SET.has(s)) return s

  for (const [prefix, sido] of PREFIX_ENTRIES) {
    if (s.startsWith(prefix)) return sido
  }
  for (const [city, sido] of CITY_ENTRIES) {
    if (s.startsWith(city)) return sido
  }
  return null
}
